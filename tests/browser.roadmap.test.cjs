const {test} = require('node:test');
const assert = require('node:assert/strict');
const path = require('node:path');
const {setupBrowser} = require('./browser-harness.cjs');

test('offline walkthrough, reset and actual example need no model or source', {timeout:90000}, async t => {
  const h = await setupBrowser(t, {name:'roadmap-offline',seed:null,planningFixture:true,viewport:{width:1280,height:800}});
  const p = h.page;
  let generationCalls = 0;
  await p.route('**/api/projects/*/planning/messages', route => { generationCalls++; return route.abort(); });
  await p.getByRole('button',{name:'Guided offline example',exact:true}).click();
  const dialog = p.getByRole('dialog',{name:'Guided offline example',exact:true});
  await dialog.getByText('Demonstration data.',{exact:true}).waitFor();
  await dialog.getByRole('button',{name:'Next',exact:true}).click();
  assert.equal(await dialog.getByRole('button',{name:'Next',exact:true}).isDisabled(),true);
  await dialog.getByRole('button',{name:'Select this proposal',exact:true}).focus();
  await p.keyboard.press('Enter');
  await dialog.getByRole('button',{name:'Next',exact:true}).click();
  await dialog.getByRole('heading',{name:'Validate records before saving',exact:true}).waitFor();
  await dialog.getByRole('button',{name:'Next',exact:true}).click();
  await dialog.getByText('Illustrative pass (not observed)',{exact:true}).waitFor();
  assert.equal(await dialog.getByRole('button',{name:'Next',exact:true}).isDisabled(),true);
  await dialog.getByRole('button',{name:'Record sample review',exact:true}).click();
  await p.screenshot({path:path.join(h.output,'offline-review.png'),fullPage:true});
  await dialog.getByRole('button',{name:'Next',exact:true}).click();
  await dialog.getByText('The sample is reviewed; your checkout has not changed.',{exact:true}).waitFor();
  assert.equal((await h.api('/projects')).projects.length,0);
  await dialog.getByRole('button',{name:'Reset walkthrough',exact:true}).click();
  await dialog.getByRole('heading',{name:'Feature request',exact:true}).waitFor();
  await dialog.getByRole('button',{name:'Next',exact:true}).click();
  assert.equal(await dialog.getByRole('button',{name:'Next',exact:true}).isDisabled(),true);
  await dialog.getByRole('button',{name:'Select this proposal',exact:true}).click();
  await dialog.getByRole('button',{name:'Next',exact:true}).click();
  await dialog.getByRole('button',{name:'Next',exact:true}).click();
  await dialog.getByRole('button',{name:'Record sample review',exact:true}).click();
  await dialog.getByRole('button',{name:'Next',exact:true}).click();
  await dialog.getByRole('button',{name:'Open example project',exact:true}).click();
  await p.getByTestId('diagram-canvas').waitFor();
  const projects = (await h.api('/projects')).projects;
  assert.equal(projects.length,1);
  const project = await h.api('/projects/'+projects[0].id);
  assert.equal(project.content.buildTasks.length,2);
  const execution = await h.api('/projects/'+projects[0].id+'/execution');
  assert.equal(execution.runs.length,0);
  assert.equal(execution.repository,null);
  assert.equal(generationCalls,0);
});

test('named alternatives preserve recovery and remain usable at a narrow viewport', {timeout:90000}, async t => {
  const h = await setupBrowser(t,{name:'roadmap-alternatives',seed:{sample:true,guided:true},planningFixture:true,viewport:{width:760,height:800}});
  const p = h.page;
  await p.getByLabel('Project actions',{exact:true}).click();
  await p.getByRole('button',{name:'Checkpoints and alternatives',exact:true}).click();
  const d = p.getByRole('dialog',{name:'Checkpoints and alternative plans',exact:true});
  await d.getByLabel('Checkpoint or alternative name',{exact:true}).fill('Baseline');
  await d.getByRole('button',{name:'Save named checkpoint',exact:true}).click();
  await d.getByText('Named checkpoint saved.',{exact:true}).waitFor();
  await d.getByLabel('Checkpoint or alternative name',{exact:true}).fill('Offline alternative');
  await d.getByLabel('Explanation or decision note',{exact:true}).fill('Keep operation local.');
  await d.getByRole('button',{name:'Duplicate as alternative',exact:true}).click();
  await d.getByText('Alternative saved. Select it when you are ready to edit it.',{exact:true}).waitFor();
  await d.getByRole('button',{name:'Select alternative',exact:true}).filter({hasNot:p.locator('[disabled]')}).last().click();
  await d.getByRole('status').filter({hasText:'Plan loaded.'}).waitFor();
  assert.ok((await h.api('/projects/'+h.initial.id+'/plans')).snapshots.some(s => s.kind==='recovery'));
  const bounds = await d.boundingBox();
  assert.ok(bounds.x>=0 && bounds.x+bounds.width<=761);
  await p.screenshot({path:path.join(h.output,'alternatives-narrow.png'),fullPage:true});
  await p.keyboard.press('Escape');
  await d.waitFor({state:'hidden'});
  await h.restart();
  assert.equal((await h.api('/projects/'+h.initial.id+'/plans')).alternatives.length,2);
});
